#!/usr/bin/env node
// Generates the dial_ui icon images from the design SVGs (the design stays the single source of truth):
//   design/components/WeatherIcon/preview.html -> components/dial_ui/weather_icons.c (48 and 32 px)
//   design/components/RoomIcon/preview.html    -> components/dial_ui/room_icons.c    (16 px)
//
// Each SVG is rendered by Chromium (Playwright) white-on-black at its native size and stored as an
// LVGL A8 image (8-bit alpha). LVGL draws A8 images as a mask in the image recolour colour, like a
// font glyph, so the icons take the `ink` colour at draw time. The design asks for icon fonts;
// building them from these stroked SVGs would need stroke-to-outline tooling, so A8 images are used
// instead (same look, same draw cost).
//
// Usage: node tools/gen_icons.js
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '..');
const SETS = [
  {
    src: 'design/components/WeatherIcon/preview.html',
    out: 'components/dial_ui/weather_icons.c',
    prefix: 'dialed_weather_',
    // Order in the preview and the WeatherIcon enum in model_weather.h; 6 at 48 px then 6 at 32 px.
    names: ['clear', 'part_cloudy', 'cloudy', 'rain', 'snow', 'storm'],
    sizes: [48, 32],
  },
  {
    src: 'design/components/RoomIcon/preview.html',
    out: 'components/dial_ui/room_icons.c',
    prefix: 'dialed_room_',
    // Order in the preview and the RoomIcon enum in model_room.h; each icon at 16 and 48 px (48 unused).
    names: ['living_room', 'bedroom', 'kitchen', 'bathroom', 'office', 'garage', 'garden', 'other'],
    sizes: [16],
  },
];

async function render(page, svg) {
  svg = svg.replace(/var\(--ink\)/g, '#fff').replace(/var\(--bg\)/g, '#000');
  if (!svg.includes('xmlns=')) svg = svg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"');
  const size = Number(/width="(\d+)"/.exec(svg)[1]);
  const alpha = await page.evaluate(async ({ svg, size }) => {
    const img = new Image();
    img.src = 'data:image/svg+xml;base64,' + btoa(svg);
    await img.decode();
    const c = document.createElement('canvas');
    c.width = size;
    c.height = size;
    const g = c.getContext('2d');
    g.fillStyle = '#000';
    g.fillRect(0, 0, size, size);
    g.drawImage(img, 0, 0, size, size);
    const d = g.getImageData(0, 0, size, size).data;
    const out = [];
    for (let i = 0; i < d.length; i += 4) out.push(d[i]);  // white on black: red = coverage
    return out;
  }, { svg, size });
  return { size, alpha };
}

function emit(set, images) {
  let c = `// GENERATED by tools/gen_icons.js from ${set.src}.\n`;
  c += '// Do not edit; re-run the script after changing the design SVGs.\n';
  c += '#include "lvgl.h"\n\n';
  for (const im of images) {
    const id = `${set.prefix}${im.name}`;
    c += `static const uint8_t ${id}_map[] = {\n`;
    for (let i = 0; i < im.alpha.length; i += 24)
      c += '  ' + im.alpha.slice(i, i + 24).map((v) => '0x' + v.toString(16).padStart(2, '0')).join(', ') + ',\n';
    c += '};\n';
    c += `const lv_image_dsc_t ${id} = {\n`;
    c += `  .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = ${im.size}, .h = ${im.size}, .stride = ${im.size}},\n`;
    c += `  .data_size = sizeof(${id}_map),\n`;
    c += `  .data = ${id}_map,\n};\n\n`;
  }
  fs.writeFileSync(path.join(ROOT, set.out), c);
  console.log(`wrote ${set.out}: ${images.map((i) => i.name).join(', ')}`);
}

async function main() {
  const browser = await chromium.launch();
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  for (const set of SETS) {
    const html = fs.readFileSync(path.join(ROOT, set.src), 'utf8');
    const svgs = html.match(/<svg[\s\S]*?<\/svg>/g) || [];
    const images = [];
    for (const svg of svgs) {
      const size = Number(/width="(\d+)"/.exec(svg)[1]);
      if (!set.sizes.includes(size)) continue;
      const n = images.filter((i) => i.size === size).length;
      if (n >= set.names.length) throw new Error(`${set.src}: more ${size} px SVGs than names`);
      const r = await render(page, svg);
      images.push({ name: `${set.names[n]}_${size}`, ...r });
    }
    const expected = set.names.length * set.sizes.length;
    if (images.length !== expected) throw new Error(`${set.src}: expected ${expected} SVGs, found ${images.length}`);
    emit(set, images);
  }
  await browser.close();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
