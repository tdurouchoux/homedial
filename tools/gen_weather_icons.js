#!/usr/bin/env node
// Generates components/dial_ui/weather_icons.c from the WeatherIcon SVGs in
// design/components/WeatherIcon/preview.html (the design stays the single source of truth).
//
// Each SVG is rendered by Chromium (Playwright) white-on-black at its native size (48 and 32 px)
// and stored as an LVGL A8 image (8-bit alpha). LVGL draws A8 images as a mask in the image
// recolour colour, like a font glyph, so the icons take the `ink` colour at draw time.
// The design asks for an icon font; building one from these stroked SVGs would need
// stroke-to-outline tooling, so A8 images are used instead (same look, same draw cost).
//
// Usage: node tools/gen_weather_icons.js
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'design/components/WeatherIcon/preview.html');
const OUT = path.join(ROOT, 'components/dial_ui/weather_icons.c');
// Order in the preview, and the enum in model_weather.h.
const NAMES = ['clear', 'part_cloudy', 'cloudy', 'rain', 'snow', 'storm'];

async function main() {
  const html = fs.readFileSync(SRC, 'utf8');
  const svgs = html.match(/<svg[\s\S]*?<\/svg>/g) || [];
  if (svgs.length !== 12) throw new Error(`expected 12 SVGs (6 at 48 px, 6 at 32 px), found ${svgs.length}`);

  const browser = await chromium.launch();
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  const images = [];
  for (let k = 0; k < svgs.length; k++) {
    let svg = svgs[k].replace(/var\(--ink\)/g, '#fff').replace(/var\(--bg\)/g, '#000');
    if (!svg.includes('xmlns=')) svg = svg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"');
    const size = Number(/width="(\d+)"/.exec(svg)[1]);
    const alpha = await page.evaluate(async ({ svg, size }) => {
      const img = new Image();
      img.src = 'data:image/svg+xml;base64,' + btoa(svg);
      await img.decode();
      const c = document.createElement('canvas');
      c.width = size;
      c.height = size;
      const g = c.getContext('2d');
      g.fillStyle = '#000';
      g.fillRect(0, 0, size, size);
      g.drawImage(img, 0, 0, size, size);
      const d = g.getImageData(0, 0, size, size).data;
      const out = [];
      for (let i = 0; i < d.length; i += 4) out.push(d[i]);  // white on black: red = coverage
      return out;
    }, { svg, size });
    images.push({ name: `${NAMES[k % 6]}_${size}`, size, alpha });
  }
  await browser.close();

  let c = '// GENERATED by tools/gen_weather_icons.js from design/components/WeatherIcon/preview.html.\n';
  c += '// Do not edit; re-run the script after changing the design SVGs.\n';
  c += '#include "lvgl.h"\n\n';
  for (const im of images) {
    c += `static const uint8_t dialed_weather_${im.name}_map[] = {\n`;
    for (let i = 0; i < im.alpha.length; i += 24)
      c += '  ' + im.alpha.slice(i, i + 24).map((v) => '0x' + v.toString(16).padStart(2, '0')).join(', ') + ',\n';
    c += '};\n';
    c += `const lv_image_dsc_t dialed_weather_${im.name} = {\n`;
    c += `  .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, .w = ${im.size}, .h = ${im.size}, .stride = ${im.size}},\n`;
    c += `  .data_size = sizeof(dialed_weather_${im.name}_map),\n`;
    c += `  .data = dialed_weather_${im.name}_map,\n};\n\n`;
  }
  fs.writeFileSync(OUT, c);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${images.map((i) => i.name).join(', ')}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
